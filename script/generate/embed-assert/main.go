package main

import (
	"bytes"
	"crypto/md5"
	"encoding/hex"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	out := flag.String("o", "", "output file path")
	cacheKeyOut := flag.String("cache-key", "", "optional Go file declaring raw-source cache key MD5")
	flag.Parse()
	if *out == "" || flag.NArg() < 1 {
		fmt.Fprintln(os.Stderr, "usage: embed-assert -o <out> [-cache-key <go>] <assertDir>  (invoked via go run ./script/generate)")
		os.Exit(2)
	}
	if err := run(*out, *cacheKeyOut, flag.Arg(0)); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(outPath, cacheKeyOut, assertDir string) error {
	names, err := listSourceFiles(assertDir)
	if err != nil {
		return err
	}

	rawHash := md5.New()
	var bodies []string
	imports := make(map[string]string)

	for _, name := range names {
		data, err := os.ReadFile(filepath.Join(assertDir, name))
		if err != nil {
			return err
		}
		if _, err := rawHash.Write(data); err != nil {
			return err
		}
		fileImports, body, err := splitImportsAndBody(name, data)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		for path, alias := range fileImports {
			if existing, ok := imports[path]; !ok || existing == "" {
				imports[path] = alias
			}
		}
		bodies = append(bodies, string(body))
	}
	rawMD5 := hex.EncodeToString(rawHash.Sum(nil))

	var merged bytes.Buffer
	merged.WriteString("// Code generated by script/generate/embed-assert; DO NOT EDIT.\n\n")
	merged.WriteString("//go:build ignore\n\n")
	merged.WriteString("package assert\n\n")
	writeImportBlock(&merged, imports)
	for _, body := range bodies {
		trimmed := strings.TrimSpace(body)
		if trimmed == "" {
			continue
		}
		merged.WriteString(trimmed)
		merged.WriteString("\n\n")
	}

	formatted, err := format.Source(merged.Bytes())
	if err != nil {
		return fmt.Errorf("format merged source: %w", err)
	}
	if err := os.WriteFile(outPath, formatted, 0644); err != nil {
		return err
	}
	if cacheKeyOut != "" {
		src := fmt.Sprintf("// Code generated by script/generate/embed-assert; DO NOT EDIT.\n\npackage assertmod\n\nconst rawSourceCacheKeyMD5 = %q\n", rawMD5)
		if err := os.WriteFile(cacheKeyOut, []byte(src), 0644); err != nil {
			return err
		}
	}
	return nil
}

func listSourceFiles(assertDir string) ([]string, error) {
	entries, err := os.ReadDir(assertDir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		name := e.Name()
		if strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	return names, nil
}

func splitImportsAndBody(filename string, src []byte) (map[string]string, []byte, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, src, parser.ParseComments)
	if err != nil {
		return nil, nil, err
	}

	imports := make(map[string]string)
	var lastDeclEnd token.Pos
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.IMPORT {
			break
		}
		for _, spec := range gen.Specs {
			imp, ok := spec.(*ast.ImportSpec)
			if !ok {
				continue
			}
			path := strings.Trim(imp.Path.Value, `"`)
			alias := ""
			if imp.Name != nil {
				alias = imp.Name.Name
			}
			imports[path] = alias
		}
		if gen.End() > lastDeclEnd {
			lastDeclEnd = gen.End()
		}
	}

	start := 0
	if lastDeclEnd > 0 {
		start = fset.Position(lastDeclEnd).Offset
	} else {
		start = fset.Position(file.Name.End()).Offset
	}
	body := bytes.TrimSpace(src[start:])
	return imports, body, nil
}

func writeImportBlock(buf *bytes.Buffer, imports map[string]string) {
	if len(imports) == 0 {
		return
	}
	paths := make([]string, 0, len(imports))
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)

	if len(paths) == 1 {
		path := paths[0]
		if alias := imports[path]; alias != "" {
			fmt.Fprintf(buf, "import %s %q\n\n", alias, path)
			return
		}
		fmt.Fprintf(buf, "import %q\n\n", path)
		return
	}

	buf.WriteString("import (\n")
	for _, path := range paths {
		if alias := imports[path]; alias != "" {
			fmt.Fprintf(buf, "\t%s %q\n", alias, path)
			continue
		}
		fmt.Fprintf(buf, "\t%q\n", path)
	}
	buf.WriteString(")\n\n")
}